"""Attached images: copied into the app's images folder, referenced by file name.

Thumbnails are generated by the UI layer (Qt) and cached in ``images/.thumbs``.
"""

from __future__ import annotations

import shutil
import uuid
from collections.abc import Iterable
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from filmlog import paths
from filmlog.db.models import Camera, Print, Roll, RollImage

IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png", ".tif", ".tiff", ".webp", ".bmp", ".gif")


def is_image_file(path: Path) -> bool:
    return path.suffix.lower() in IMAGE_EXTENSIONS


def import_image(src: Path, images_dir: Path | None = None) -> str:
    """Copy ``src`` into the images folder under a unique name; return that name."""
    images_dir = images_dir or paths.images_dir()
    if not src.is_file():
        raise FileNotFoundError(src)
    if not is_image_file(src):
        raise ValueError(f"Not a supported image type: {src.suffix}")
    images_dir.mkdir(parents=True, exist_ok=True)
    stem = "".join(c if c.isalnum() or c in "-_" else "_" for c in src.stem)[:40] or "image"
    name = f"{stem}-{uuid.uuid4().hex[:8]}{src.suffix.lower()}"
    shutil.copy2(src, images_dir / name)
    return name


def image_path(name: str, images_dir: Path | None = None) -> Path:
    return (images_dir or paths.images_dir()) / name


def delete_image_files(
    names: Iterable[str | None],
    images_dir: Path | None = None,
    thumbs_dir: Path | None = None,
) -> int:
    """Remove image files and their cached thumbnails. Returns files removed."""
    images_dir = images_dir or paths.images_dir()
    thumbs_dir = thumbs_dir or paths.thumbnails_dir()
    removed = 0
    for name in names:
        if not name or "/" in name or "\\" in name or name.startswith("."):
            continue  # never touch anything outside the images folder
        p = images_dir / name
        if p.is_file():
            p.unlink()
            removed += 1
        if thumbs_dir.is_dir():
            for t in thumbs_dir.glob(f"{Path(name).stem}_*"):
                t.unlink(missing_ok=True)
    return removed


def referenced_images(session: Session) -> set[str]:
    names: set[str] = set()
    for col in (Camera.photo, Roll.contact_sheet_image, Print.image, RollImage.filename):
        names.update(n for n in session.scalars(select(col).where(col.is_not(None))) if n)
    return names


def delete_unreferenced(session: Session, candidates: Iterable[str | None]) -> int:
    """Delete candidate files that no record references any more."""
    used = referenced_images(session)
    return delete_image_files(n for n in candidates if n and n not in used)


def images_of_roll(roll: Roll) -> list[str]:
    """All image files owned by a roll, including its prints' images."""
    names = [roll.contact_sheet_image] + [i.filename for i in roll.images]
    names += [p.image for p in roll.prints]
    return [n for n in names if n]


def orphan_files(session: Session, images_dir: Path | None = None) -> list[Path]:
    images_dir = images_dir or paths.images_dir()
    if not images_dir.is_dir():
        return []
    used = referenced_images(session)
    return [p for p in images_dir.iterdir() if p.is_file() and p.name not in used]
